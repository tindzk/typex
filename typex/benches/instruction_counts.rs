#[derive(Clone)]
struct EntryMap {
  entries: Vec<(String, u8)>,
}

impl Meta for EntryMap {
  fn reflect(&self) -> Reflect<'_> {
    Reflect::Map(self)
  }

  fn into_any(self: Box<Self>) -> Box<dyn Any> {
    self
  }

  fn as_any(&self) -> &dyn Any {
    self
  }
}

impl MapAccess for EntryMap {
  fn len(&self) -> usize {
    self.entries.len()
  }

  fn key(&self, key: &str) -> Option<ObjectRef<'_>> {
    self
      .entries
      .iter()
      .find(|(entry_key, _)| entry_key == key)
      .map(|(_, value)| ObjectRef::new(value))
  }

  fn keys(&self) -> Option<Vec<String>> {
    Some(self.entries.iter().map(|(key, _)| key.clone()).collect())
  }

  fn visit_entries(&self, visitor: &mut MapEntryVisitor<'_>) {
    for (key, value) in &self.entries {
      if !visitor(AnyRef::new(key), ObjectRef::new(value)) {
        break;
      }
    }
  }
}

fn equality_input() -> (EntryMap, EntryMap) {
  let left = EntryMap {
    entries: vec![
      (String::from("primary"), 1_u8),
      (String::from("secondary"), 2_u8),
    ],
  };
  (left.clone(), left)
}

fn derived_equality_input() -> (PatchState, PatchState) {
  (state(), state())
}

#[library_benchmark]
#[bench::default(setup = derived_equality_input)]
fn derived_struct_equality((left, right): (PatchState, PatchState)) -> bool {
  black_box(ObjectRef::new(&left).eq_dyn(ObjectRef::new(&right)))
}

#[library_benchmark]
#[bench::default(setup = equality_input)]
fn generic_map_equality((left, right): (EntryMap, EntryMap)) -> bool {
  black_box(ObjectRef::new(&left).eq_dyn(ObjectRef::new(&right)))
}

